  var esc = SI.esc;

  function money(value) {
    var n = Number(value);
    if (!isFinite(n)) return 'custom';
    return '$' + n.toFixed(2);
  }

  function money4(value) {
    var n = Number(value);
    if (!isFinite(n)) return '';
    return '$' + n.toFixed(4);
  }

  function field(label, input, hint) {
    return '<label class="field"><span class="field__label">' + esc(label) + '</span>' + input +
      (hint ? '<span class="field__hint">' + esc(hint) + '</span>' : '') + '</label>';
  }

  function statusBox(id) {
    return '<div class="form-error" id="' + id + '" hidden></div>';
  }

  function showError(id, message) {
    var node = document.getElementById(id);
    if (!node) return;
    node.textContent = message;
    node.hidden = false;
    var anchor = node.scrollIntoView ? node : null;
    if (anchor) anchor.scrollIntoView({ block: 'nearest', behavior: SI.reduced ? 'auto' : 'smooth' });
  }

  function clearError(id) {
    var node = document.getElementById(id);
    if (node) { node.hidden = true; node.textContent = ''; }
  }

  /* Every public write goes through here so failures always land in the same
     place instead of silently doing nothing. */
  function submit(path, body, errorId, onDone) {
    clearError(errorId);
    var busy = document.querySelector('[data-busy]');
    if (busy) busy.disabled = true;
    SI.api.post(path, body).then(function (data) {
      if (busy) busy.disabled = false;
      onDone(data);
    }).catch(function (err) {
      if (busy) busy.disabled = false;
      showError(errorId, err.message);
      /* A spent or wrong human check cannot be reused, so mint a new one. */
      if (err.code === 'human_failed' || err.code === 'human_required') human.reload();
    });
  }

  /* ---------------------------------------------------------
     the custom verify-you-are-human
     --------------------------------------------------------- */
  var human = (function () {
    var box = null;
    var state = { token: '', answer: '', kind: '' };

    function paint() {
      if (!box) return;
      if (state.kind === 'choice') {
        box.innerHTML =
          '<span class="human__label">Verify you are human</span>' +
          '<p class="human__prompt">' + esc(state.prompt) + '</p>' +
          '<div class="human__choices">' +
            state.choices.map(function (choice) {
              return '<button type="button" class="human__choice" data-answer="' + esc(choice) + '">' +
                esc(choice) + '</button>';
            }).join('') +
          '</div>' +
          '<p class="human__status" id="humanStatus">Pick one. The check resets if you are wrong.</p>';
        return;
      }
      box.innerHTML =
        '<span class="human__label">Verify you are human</span>' +
        '<p class="human__prompt">' + esc(state.prompt) + '</p>' +
        '<div class="human__row">' +
          '<input type="text" inputmode="numeric" autocomplete="off" id="humanInput" placeholder="' +
            esc(state.placeholder || 'answer') + '">' +
        '</div>' +
        '<p class="human__status" id="humanStatus">The check resets if you are wrong.</p>';
      /* Deliberately no focus() here. Auto-focusing a field near the bottom of
         the form scrolls the page the moment it loads, which reads as a jump. */
    }

    function load() {
      if (!box) return;
      var heading = '<span class="human__label">Verify you are human</span>';
      /* The question is generated by the server, so on a static build there is
         nothing to ask and nothing to check the answer against. Saying so beats
         showing "The server sent something unreadable", which is what a 404 on
         /api/human produces and which reads as the site being broken rather
         than as a form that cannot be submitted here. */
      if (SI.api.static) {
        box.innerHTML = heading +
          '<p class="human__status">Not needed on this build of the site. ' +
          'This form cannot be sent - please reach us on Discord.</p>';
        return;
      }
      box.innerHTML = heading + '<p class="human__status">Loading…</p>';
      SI.api.get('/api/human').then(function (data) {
        state.token = data.token;
        state.prompt = data.prompt;
        state.choices = data.choices || [];
        state.placeholder = data.placeholder || 'answer';
        state.kind = data.kind;
        state.answer = '';
        paint();
      }).catch(function (err) {
        box.innerHTML = heading +
          '<p class="human__status is-bad">' + esc(err.message) + '</p>';
      });
    }

    function mount(selector) {
      box = document.querySelector(selector);
      if (!box) return;
      box.addEventListener('click', function (event) {
        var choice = event.target.closest('.human__choice');
        if (!choice) return;
        state.answer = choice.getAttribute('data-answer');
        box.querySelectorAll('.human__choice').forEach(function (node) {
          node.classList.toggle('is-picked', node === choice);
        });
        var status = document.getElementById('humanStatus');
        if (status) { status.textContent = 'Picked. Send the form to confirm.'; status.className = 'human__status is-good'; }
      });
      load();
    }

    function result() {
      var typed = document.getElementById('humanInput');
      var answer = state.kind === 'choice' ? state.answer : (typed ? typed.value : '');
      return { token: state.token, answer: String(answer || '').trim() };
    }

    return { mount: mount, reload: load, result: result };
  }());

