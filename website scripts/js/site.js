    /* The catalog exposes one Stripe processor, not each of its payment methods. */
    var PAY_LABELS = { stripe: 'Stripe secure checkout' };

    function renderPay() {
      var pay = cat.payments;
      var host = document.getElementById('payOptions');
      var availability = cat.provider_availability || {};
      var ready = cat.providers_configured.stripe;

      var options = [];
      pay.providers.concat(pay.manual_review).forEach(function (id) {
        var info = availability[id] || { available: false, instant: false, reason: '' };
        options.push({
          id: id,
          label: PAY_LABELS[id] || id.charAt(0).toUpperCase() + id.slice(1),
          note: info.reason || (ready ? 'Checkout opens next.' : 'No provider connected yet.'),
          available: info.available !== false,
          instant: !!info.instant
        });
      });

      /* Stripe presents eligible methods enabled on its Dashboard in one hosted checkout. */
      var rank = function (o) { return o.available ? (o.instant ? 0 : 1) : 2; };
      options.sort(function (a, b) { return rank(a) - rank(b); });
      var firstUsable = options.filter(function (o) { return o.available; })[0];
      var defaultId = firstUsable ? firstUsable.id : '';
      var anyInstant = options.some(function (o) { return o.instant; });

      host.innerHTML = options.map(function (option) {
        var on = option.id === defaultId;
        return '<label class="pay-option' + (on ? ' is-on' : '') + (option.available ? '' : ' is-off') + '">' +
          '<input class="pay-option__radio" type="radio" name="provider" value="' + esc(option.id) + '"' +
            (on ? ' checked' : '') + (option.available ? '' : ' disabled') + '>' +
          '<span class="pay-option__text">' +
            '<b>' + esc(option.label) + '</b>' +
            '<span class="pay-option__note">' + esc(option.note) + '</span>' +
          '</span></label>';
      }).join('');

      /* A disabled input is never "changed", so the highlight is set from the
         checked state on every change rather than only on the clicked one. */
      host.addEventListener('change', function () {
        host.querySelectorAll('.pay-option').forEach(function (node) {
          var input = node.querySelector('input');
          node.classList.toggle('is-on', !!input && input.checked);
        });
        updatePayReady();
      });

      /* Warn when Stripe is not configured; manual payment methods are not exposed. */
      var notice = document.getElementById('payNotice');
      if (notice) notice.hidden = anyInstant;
      updatePayReady();
    }

