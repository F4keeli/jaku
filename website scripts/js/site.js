  function resumeAfterPayment() {
    /* Stripe returns with the order reference; its signed webhook settles the order. */
    var params = new URLSearchParams(window.location.search);
    var paid = (params.get('paid') || '').trim().toUpperCase();
    var cancelled = (params.get('cancelled') || '').trim().toUpperCase();
    var provider = (params.get('provider') || '').trim().toLowerCase();
    if (!paid && !cancelled) return;
    if (!/^SI-[0-9A-Z]{6}$/.test(paid) && !/^SI-[0-9A-Z]{6}$/.test(cancelled)) return;

    var box = SI.$('#orderDone');
    var note = SI.$('#orderNote');
    var refNode = SI.$('#orderRef');

    if (cancelled) {
      if (box) box.hidden = false;
      if (refNode) refNode.textContent = cancelled;
      if (note) {
        note.textContent = 'You cancelled at Stripe Checkout' +
          '. Nothing has been charged and the order is still waiting.';
      }
      if (window.history && window.history.replaceState) {
        window.history.replaceState({}, '', window.location.pathname);
      }
      return;
    }

    if (provider === 'paypal') {
      if (box) box.hidden = false;
      if (refNode) refNode.textContent = paid;
      if (note) note.textContent = 'This store accepts payment through Stripe Checkout only.';
      if (window.history && window.history.replaceState) {
        window.history.replaceState({}, '', window.location.pathname);
      }
      return;
    }
    if (provider === 'stripe' || provider === 'card' || provider === 'cashapp' || !provider) {
      var discordId = window.prompt(
        'Payment submitted. Enter the Discord ID used for this order to check its status:',
        window.localStorage.getItem('si:lastDiscordId') || ''
      );
      if (box) box.hidden = false;
      if (refNode) refNode.textContent = paid;
      if (discordId) {
        discordId = discordId.trim();
        window.localStorage.setItem('si:lastDiscordId', discordId);
        if (note) note.textContent = 'Waiting for the payment provider’s signed confirmation…';
        var attempts = 0;
        var poll = function () {
          SI.api.post('/api/store/order/lookup', { ref: paid, discord_id: discordId })
            .then(function (order) {
              if (note) note.textContent = order.status === 'paid' || order.status === 'delivered'
                ? 'Payment confirmed. Your order is recorded for staff fulfillment.'
                : 'The order is still ' + String(order.status).replace(/_/g, ' ') + '. Use “Look up an order” to check again shortly.';
            })
            .catch(function () {
              attempts += 1;
              if (attempts < 6) {
                window.setTimeout(poll, 1500);
              } else if (note) {
                note.textContent = 'Payment confirmation is still pending. Keep this reference and use “Look up an order” to check again shortly.';
              }
            });
        };
        poll();
      } else if (note) {
        note.textContent = 'Payment confirmation is pending. Keep this reference and use “Look up an order” when you have your Discord ID.';
      }
      if (window.history && window.history.replaceState) {
        window.history.replaceState({}, '', window.location.pathname);
      }
      return;
    }

    if (box) box.hidden = false;
    if (refNode) refNode.textContent = paid;
    if (note) note.textContent = 'This payment return is not supported. Start checkout again through Stripe.';
  }

