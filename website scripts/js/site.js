  function pageContact() {
    var form = SI.$('#contactForm');
    if (!form) return;

    SI.api.get('/api/site').then(function (data) {
      var topics = (data && data.contact && data.contact.topics) || [];
      var picker = document.getElementById('topic');
      if (picker && !picker.options.length) {
        picker.innerHTML = topics.map(function (topic, i) {
          return '<option value="' + esc(topic.id) + '"' + (i === 0 ? ' selected' : '') + '>' +
            esc(topic.label) + '</option>';
        }).join('');
      }
      var inbox = document.getElementById('contactInbox');
      if (inbox && data && data.contact && data.contact.inbox) inbox.textContent = data.contact.inbox;
    });

    human.mount('#humanBox');

    form.addEventListener('submit', function (event) {
      event.preventDefault();
      var data = new FormData(form);
      var check = human.result();
      submit('/api/contact', {
        topic: data.get('topic'),
        discord_username: data.get('discord_username'),
        discord_id: data.get('discord_id'),
        name: data.get('name'),
        email: data.get('email'),
        message: data.get('message'),
        website: data.get('website'),
        human: check.token,
        answer: check.answer
      }, 'contactError', function (result) {
        form.hidden = true;
        var done = SI.$('#contactDone');
        if (done) {
          done.hidden = false;
          document.getElementById('contactRef').textContent = result.ref;
          document.getElementById('contactNote').textContent = result.message;
        }
      });
    });
  }

