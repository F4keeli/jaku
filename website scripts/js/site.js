  function pageTeam() {
    var list = SI.$('#tierList');
    var note = SI.$('#teamNote');
    if (!list) return;

    SI.api.get('/api/site').then(function (data) {
      var team = (data && data.team) || {};
      var hierarchy = team.hierarchy || [];
      var groups = team.groups || [];
      var total = groups.reduce(function (sum, group) {
        return sum + ((group.members || []).length);
      }, 0);
      if (note) {
        note.textContent = total + ' ' + (total === 1 ? 'person' : 'people') + ' across ' +
          groups.length + ' ' + (groups.length === 1 ? 'tier' : 'tiers') + '.';
      }
      if (!total) {
        list.innerHTML = SI.empty('The roster is empty',
          'Add people from the panel under Leadership › Staff Configuration.');
        return;
      }
      list.innerHTML = groups.map(function (group) {
        var label = group.label || group.key;
        var members = (group.members || []).map(function (member) {
          /* The rank line is "tier · job title", but on most tiers a member's
             title is the same word as the tier ("Owner · Owner"), which read as
             a stutter. Only the second half is printed when the two actually
             differ, and the comparison ignores case and stray whitespace
             because the two are typed independently in the panel. */
          var title = String(member.title || '').trim();
          var same = title.toLowerCase() === String(label).trim().toLowerCase();
          var rank = same || !title ? esc(label) : esc(label) + ' &middot; ' + esc(title);
          var discordId = String(member.discord_id || '').trim();
          var discordProfile = /^[0-9]{17,20}$/.test(discordId)
            ? '<p class="muted small mono">Discord ID: <a href="https://discord.com/users/' +
              discordId + '" target="_blank" rel="noopener noreferrer">' + esc(discordId) + '</a></p>'
            : '';
          return '<div class="person' + (label === 'Leadership' ? ' person--lead' : '') + '">' +
            '<div class="person__face">' + SI.memberFace(member) + '</div>' +
            '<div>' +
              '<h3 class="person__name">' + esc(member.name) + '</h3>' +
              '<p class="person__rank">' + rank + '</p>' +
              discordProfile +
              (member.blurb ? '<p class="person__blurb">' + esc(member.blurb) + '</p>' : '') +
            '</div>' +
          '</div>';
        }).join('');
        return '<section class="tier reveal">' +
          '<div class="tier__head"><h2 class="tier__name">' + esc(label) + '</h2>' +
            '<span class="tier__count">' + (group.members || []).length + '</span></div>' +
          (group.blurb ? '<p class="tier__blurb">' + esc(group.blurb) + '</p>' : '') +
          /* The roles that exist in the tier, whether or not anyone holds them
             yet. Without this a tier reads as one job: the old shape had the
             role as the group label, so "Leadership" appeared as "Owner" and
             Compliance Officer had nowhere to live. */
          (group.roles && group.roles.length
            ? '<ul class="roles">' + group.roles.map(function (role) {
                var held = (group.members || []).some(function (member) {
                  return String(member.title || '').trim() === role;
                });
                return '<li class="role' + (held ? ' role--held' : '') + '">' +
                  esc(role) + '</li>';
              }).join('') + '</ul>'
            : '') +
          /* The members need the .roster grid. They used to be dropped straight
             into the section, which is a block, so every person rendered as one
             full-width row however many there were and the .roster rule in
             pages.css was never applied to anything. */
          '<div class="roster">' +
            (members || SI.empty('No one in this tier yet')) +
          '</div>' +
        '</section>';
      }).join('');
      if (hierarchy.length) {
        list.insertAdjacentHTML('afterbegin',
          '<p class="muted small" style="margin-bottom:1.2rem">Hierarchy: ' +
          esc(hierarchy.join(' › ')) + '</p>');
      }
      list.insertAdjacentHTML('beforeend', creditsBlock(team));
      SI.observeReveal(list);
    }).catch(function (err) {
      list.innerHTML = SI.empty('Could not load the roster', err.message);
    });
  }

