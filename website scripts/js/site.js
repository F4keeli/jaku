  function pageApplications() {
    var list = SI.$('#roleList');
    var note = SI.$('#roleNote');
    var panel = SI.$('#applyPanel');
    if (!list) return;

    var roles = [];
    SI.api.get('/api/applications').then(function (data) {
      roles = (data && data.roles) || [];
      var open = roles.filter(function (role) { return role.open; });
      if (note) {
        note.textContent = roles.length
          ? roles.length + ' role' + (roles.length === 1 ? '' : 's') + ' listed, ' +
            open.length + ' accepting applications.'
          : 'No roles are listed right now.';
      }
      if (!roles.length) {
        list.innerHTML = SI.empty('Nothing to apply for',
          'Roles added in the panel appear here automatically.');
        return;
      }
      list.innerHTML = roles.map(function (role) {
        return '<article class="role-card reveal ' + (role.open ? 'is-open' : 'is-closed') +
            '" id="role-' + esc(role.id) + '">' +
          '<div class="panel-box__head">' +
            '<h2 class="panel-box__title">' + esc(role.role) + '</h2>' +
            (role.open
              ? '<span class="tag tag--live">Open</span>'
              : '<span class="tag">' + esc(role.closed_reason || 'Closed') + '</span>') +
            (role.closes_at ? '<span class="tag tag--ghost">Closes ' + esc(role.closes_at.slice(0, 10)) + '</span>' : '') +
          '</div>' +
          '<p class="page__desc" style="margin-top:0">' + esc(role.summary) + '</p>' +
          (role.responsibilities.length || role.requirements.length
            ? '<div class="role-card__cols">' +
                (role.responsibilities.length
                  ? '<div><h4>What you would do</h4><ul class="bullets">' +
                    role.responsibilities.map(function (r) { return '<li>' + esc(r) + '</li>'; }).join('') + '</ul></div>'
                  : '') +
                (role.requirements.length
                  ? '<div><h4>What we need</h4><ul class="bullets">' +
                    role.requirements.map(function (r) { return '<li>' + esc(r) + '</li>'; }).join('') + '</ul></div>'
                  : '') +
              '</div>'
            : '') +
          '<div class="role-card__foot">' +
            '<span class="role-card__stat">' + role.applicants + ' applicant' + (role.applicants === 1 ? '' : 's') + '</span>' +
            (role.open
              ? '<button class="btn btn--primary" type="button" data-apply="' + esc(role.id) + '"><span>Apply</span></button>'
              : '<span class="muted small">Not accepting applications</span>') +
          '</div>' +
        '</article>';
      }).join('');
      SI.observeReveal(list);
    }).catch(function (err) {
      list.innerHTML = SI.empty('Could not load roles', err.message);
    });

    list.addEventListener('click', function (event) {
      var button = event.target.closest('[data-apply]');
      if (!button || !panel) return;
      var role = roles.filter(function (r) { return r.id === button.getAttribute('data-apply'); })[0];
      if (!role) return;
      panel.hidden = false;
      document.getElementById('applyTitle').textContent = 'Apply: ' + role.role;
      document.getElementById('applyIntro').textContent = role.summary;
      document.getElementById('applyFields').innerHTML = role.questions.map(function (q) {
        var req = q.required ? '<span class="req">*</span>' : '';
        /* The name has to be on the element, not just the id: the answers are
           collected with FormData, which keys off name. */
        var nameAttr = ' name="q_' + esc(q.id) + '" id="q_' + esc(q.id) + '"';
        var input = q.type === 'textarea'
          ? '<textarea' + nameAttr + (q.required ? ' required' : '') + '></textarea>'
          : q.type === 'select'
            ? '<select' + nameAttr + (q.required ? ' required' : '') + '>' +
                '<option value="">Choose…</option>' +
                q.options.map(function (o) { return '<option value="' + esc(o) + '">' + esc(o) + '</option>'; }).join('') +
              '</select>'
            : '<input type="' + (q.type === 'number' ? 'number' : 'text') + '"' + nameAttr +
              (q.required ? ' required' : '') + '>';
        return field(q.label + req, input, q.hint);
      }).join('');
      document.getElementById('applyRole').value = role.id;
      human.reload();
      panel.scrollIntoView({ behavior: SI.reduced ? 'auto' : 'smooth', block: 'start' });
    });

    var form = SI.$('#applyForm');
    if (!form) return;
    var cancel = document.getElementById('applyCancel');
    if (cancel) {
      cancel.addEventListener('click', function () {
        if (panel) panel.hidden = true;
      });
    }
    form.addEventListener('submit', function (event) {
      event.preventDefault();
      var data = new FormData(form);
      var answers = {};
      roles.forEach(function (role) {
        role.questions.forEach(function (q) {
          var value = data.get('q_' + q.id);
          if (value) answers[q.id] = String(value);
        });
      });
      var check = human.result();
      submit('/api/application', {
        role: data.get('role'),
        name: data.get('name'),
        email: data.get('email'),
        answers: answers,
        website: data.get('website'),
        human: check.token,
        answer_human: check.answer
      }, 'applyError', function (result) {
        form.hidden = true;
        var done = SI.$('#applyDone');
        if (done) {
          done.hidden = false;
          document.getElementById('applyRef').textContent = result.ref;
          document.getElementById('applyNote').textContent = result.message;
        }
      });
    });
  }

