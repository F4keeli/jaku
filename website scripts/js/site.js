          cart: cart,
          code: code,
          discord_id: data.get('discord_id'),
          discord_name: data.get('discord_name'),
          email: data.get('email'),
          provider: data.get('provider'),
          /* The postal code is sent, never an amount. The server prices the
             cart, works out the tax and returns the total it will charge. */
